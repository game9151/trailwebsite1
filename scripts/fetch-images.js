#!/usr/bin/env node
/**
 * scripts/fetch-images.js
 * ---------------------------------------------------------------------------
 * Downloads real, free-licence photos for the page's image slots and saves
 * them with the exact filenames the site expects (see site.config.js).
 *
 * Keys are read from the environment / a local .env file and NEVER written
 * into code or committed (.env is gitignored):
 *   PEXELS_API_KEY        — https://www.pexels.com/api/   (preferred)
 *   UNSPLASH_ACCESS_KEY   — https://unsplash.com/developers
 *
 * Usage:
 *   node scripts/fetch-images.js
 *
 * Resizing/compression: if `sharp` is installed it will resize to <=1600px
 * wide and compress to keep files small. If not, images are saved as-is and
 * the script tells you how to add compression. No photo? The page already has
 * matching SVG illustrations, so nothing breaks.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const IMAGES_DIR = path.join(ROOT, "images");
const CREDITS = path.join(ROOT, "CREDITS.md");
const CONFIG = path.join(ROOT, "site.config.js");

// ---- The image slots the page actually uses ------------------------------
// filename, target size, search query, and what it should show.
const MANIFEST = [
  { file: "hero-workshop.jpg", query: "car mechanic working under car on lift", orientation: "landscape", shows: "Hero — technician working on a raised car" },
  { file: "workshop.jpg", query: "auto repair garage workshop interior bay", orientation: "landscape", shows: "Service-area panel — the workshop/garage" },
  { file: "team.jpg", query: "mechanic team portrait auto shop", orientation: "portrait", shows: "Why-choose-us panel — the technician team" },
];

// ---- Minimal .env loader (no dependency) ---------------------------------
function loadEnv() {
  const envPath = path.join(ROOT, ".env");
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !(m[1] in process.env)) {
      process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, "");
    }
  }
}

// ---- Optional sharp for resize/compress ----------------------------------
let sharp = null;
try { sharp = require("sharp"); } catch { /* optional */ }

async function processImage(buffer, destPath) {
  if (sharp) {
    await sharp(buffer)
      .resize({ width: 1600, withoutEnlargement: true })
      .jpeg({ quality: 78, mozjpeg: true })
      .toFile(destPath);
    const kb = Math.round(fs.statSync(destPath).size / 1024);
    return `${kb} KB (resized/compressed)`;
  }
  fs.writeFileSync(destPath, buffer);
  const kb = Math.round(buffer.length / 1024);
  return `${kb} KB (raw — install \`sharp\` to compress)`;
}

// ---- Providers -----------------------------------------------------------
async function searchPexels(query, orientation, key) {
  const url = `https://api.pexels.com/v1/search?query=${encodeURIComponent(query)}&per_page=1&orientation=${orientation}`;
  const r = await fetch(url, { headers: { Authorization: key } });
  if (!r.ok) throw new Error(`Pexels ${r.status}`);
  const data = await r.json();
  const p = data.photos && data.photos[0];
  if (!p) return null;
  return { downloadUrl: p.src.large2x || p.src.large || p.src.original, photographer: p.photographer, link: p.url, source: "Pexels", licence: "Pexels Licence (free, no attribution required)" };
}

async function searchUnsplash(query, orientation, key) {
  const url = `https://api.unsplash.com/search/photos?query=${encodeURIComponent(query)}&per_page=1&orientation=${orientation}`;
  const r = await fetch(url, { headers: { Authorization: `Client-ID ${key}` } });
  if (!r.ok) throw new Error(`Unsplash ${r.status}`);
  const data = await r.json();
  const p = data.results && data.results[0];
  if (!p) return null;
  // Unsplash guideline: trigger a download event.
  if (p.links && p.links.download_location) {
    fetch(p.links.download_location, { headers: { Authorization: `Client-ID ${key}` } }).catch(() => {});
  }
  return { downloadUrl: p.urls.regular, photographer: p.user && p.user.name, link: p.links && p.links.html, source: "Unsplash", licence: "Unsplash Licence (free, attribution appreciated)" };
}

function writeCredits(entries) {
  const block =
    "<!-- PHOTO-CREDITS:START -->\n" +
    "## Downloaded photos\n\n" +
    "_Generated by `scripts/fetch-images.js` on " + new Date().toISOString().slice(0, 10) + "._\n\n" +
    entries.map((e) =>
      `- **${e.file}** — ${e.shows}. Photo by ${e.photographer || "unknown"} on ${e.source} (${e.link || "link n/a"}). ${e.licence}.`
    ).join("\n") +
    "\n<!-- PHOTO-CREDITS:END -->";

  let md = fs.existsSync(CREDITS) ? fs.readFileSync(CREDITS, "utf8") : "# Image credits\n\n";
  if (md.includes("<!-- PHOTO-CREDITS:START -->")) {
    md = md.replace(/<!-- PHOTO-CREDITS:START -->[\s\S]*?<!-- PHOTO-CREDITS:END -->/, block);
  } else {
    md += "\n\n" + block + "\n";
  }
  fs.writeFileSync(CREDITS, md);
}

(async function main() {
  loadEnv();
  const pexelsKey = process.env.PEXELS_API_KEY;
  const unsplashKey = process.env.UNSPLASH_ACCESS_KEY;

  if (!pexelsKey && !unsplashKey) {
    console.log("No PEXELS_API_KEY or UNSPLASH_ACCESS_KEY found.");
    console.log("Add one to a local .env file and re-run, or just deploy —");
    console.log("the page already renders with built-in SVG illustrations.");
    process.exit(0);
  }

  fs.mkdirSync(IMAGES_DIR, { recursive: true });
  const provider = pexelsKey ? "Pexels" : "Unsplash";
  console.log(`Fetching ${MANIFEST.length} images via ${provider}…\n`);

  const credits = [];
  for (const item of MANIFEST) {
    try {
      const hit = pexelsKey
        ? await searchPexels(item.query, item.orientation, pexelsKey)
        : await searchUnsplash(item.query, item.orientation, unsplashKey);
      if (!hit) { console.warn(`  ✗ ${item.file}: no match (SVG fallback will show)`); continue; }

      const imgRes = await fetch(hit.downloadUrl);
      if (!imgRes.ok) throw new Error(`download ${imgRes.status}`);
      const buffer = Buffer.from(await imgRes.arrayBuffer());
      const dest = path.join(IMAGES_DIR, item.file);
      const info = await processImage(buffer, dest);

      credits.push({ ...item, ...hit });
      console.log(`  ✓ ${item.file} — ${info} — © ${hit.photographer} / ${hit.source}`);
    } catch (err) {
      console.warn(`  ✗ ${item.file}: ${err.message} (SVG fallback will show)`);
    }
  }

  if (credits.length) {
    writeCredits(credits);
    console.log(`\nUpdated CREDITS.md with ${credits.length} photo credit(s).`);
    // Turn on photos in the config so the downloaded images actually show.
    try {
      let cfg = fs.readFileSync(CONFIG, "utf8");
      if (/usePhotos:\s*false/.test(cfg)) {
        cfg = cfg.replace(/usePhotos:\s*false/, "usePhotos: true");
        fs.writeFileSync(CONFIG, cfg);
        console.log("Set images.usePhotos = true in site.config.js.");
      }
    } catch (e) {
      console.warn("Could not auto-enable photos — set images.usePhotos: true in site.config.js manually.");
    }
  }
  console.log("\nDone. Re-run anytime after changing queries in this script.");
})();
